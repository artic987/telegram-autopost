def font(size, bold=False):
    paths = [
        "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
        if bold else
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Bold.ttf"
        if bold else
        "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
    ]

    for path in paths:
        if Path(path).exists():
            return ImageFont.truetype(path, size)

    return ImageFont.load_default()


def make_avatar():
    size = 800
    img = Image.new("RGB", (size, size))
    px = img.load()

    # мягкий рассветный градиент
    for y in range(size):
        t = y / (size - 1)

        r = int(205 * (1-t) + 235 * t)
        g = int(220 * (1-t) + 214 * t)
        b = int(245 * (1-t) + 205 * t)

        for x in range(size):
            px[x, y] = (r, g, b)

    d = ImageDraw.Draw(img)

    # дальние горы
    d.polygon(
        [
            (0, 480),
            (110, 400),
            (220, 445),
            (340, 350),
            (470, 430),
            (610, 325),
            (800, 440),
            (800, 800),
            (0, 800),
        ],
        fill=(92, 139, 181),
    )

    # ближние горы
    d.polygon(
        [
            (0, 570),
            (150, 470),
            (285, 545),
            (430, 445),
            (560, 530),
            (700, 430),
            (800, 500),
            (800, 800),
            (0, 800),
        ],
        fill=(42, 100, 151),
    )

    # вода
    d.rectangle(
        (0, 600, 800, 800),
        fill=(57, 125, 174),
    )

    # блик
    d.ellipse(
        (355, 470, 445, 560),
        fill=(248, 224, 198),
    )

    # полупрозрачный светлый блок под название
    d.rounded_rectangle(
        (75, 95, 725, 310),
        radius=40,
        fill=(245, 248, 252),
    )

    title_font = font(86, True)
    sub_font = font(31, False)

    title = "FLUOXETI"
    subtitle = "ПРОСТО О СЛОЖНОМ"

    bbox = d.textbbox(
        (0, 0),
        title,
        font=title_font
    )

    tw = bbox[2] - bbox[0]

    d.text(
        ((size - tw) / 2, 125),
        title,
        font=title_font,
        fill=(25, 70, 120),
    )

    bbox = d.textbbox(
        (0, 0),
        subtitle,
        font=sub_font
    )

    sw = bbox[2] - bbox[0]

    d.text(
        ((size - sw) / 2, 235),
        subtitle,
        font=sub_font,
        fill=(45, 82, 120),
    )

    img.save(
        AVATAR,
        quality=94,
        subsampling=0
    )


async def main():
    api_id = int(os.environ["TG_API_ID"])
    api_hash = os.environ["TG_API_HASH"]
    session = os.environ["TG_STRING_SESSION"]

    make_avatar()

    async with TelegramClient(
        StringSession(session),
        api_id,
        api_hash
    ) as client:

        entity = await client.get_entity(CHANNEL)

        print("Telegram подключён.")
        print("Канал:", CHANNEL)

        # ---------- АВАТАР ----------
        try:
            uploaded = await client.upload_file(
                AVATAR
            )

            await client(
                functions.channels.EditPhotoRequest(
                    channel=entity,
                    photo=types.InputChatUploadedPhoto(
                        file=uploaded
                    )
                )
            )

            print("✓ Аватар установлен")

        except Exception as exc:
            # Посты всё равно публикуем,
            # даже если у аккаунта нет права менять фото.
            print(
                "⚠ Не удалось поменять аватар:",
                repr(exc)
            )

        # ---------- ИДЕМПОТЕНТНОСТЬ ----------
        existing = []

        async for message in client.iter_messages(
            entity,
            limit=100
        ):
            text = (
                message.message or ""
            ).strip()

            if text:
                existing.append(text)

        published = 0
        skipped = 0

        # ---------- 10 ПОСТОВ ----------
        for number, post in enumerate(
            POSTS,
            start=1
        ):
            # первая строка используется как уникальный маркер
            marker = post.splitlines()[0].strip()

            if any(
                marker in old
                for old in existing
            ):
                print(
                    f"↷ Пост {number} уже есть: "
                    f"{marker}"
                )
                skipped += 1
                continue

            msg = await client.send_message(
                entity,
                post,
                link_preview=False
            )

            existing.append(post)
            published += 1

            print(
                f"✓ Пост {number}/10 "
                f"message_id={msg.id}"
            )

            await asyncio.sleep(2)

        print()
        print("==============================")
        print("ГОТОВО")
        print("Аватар: установлен/проверен")
        print("Новых постов:", published)
        print("Пропущено существующих:", skipped)
        print("Канал:", CHANNEL)
        print("==============================")


if __name__ == "__main__":
    asyncio.run(main())
